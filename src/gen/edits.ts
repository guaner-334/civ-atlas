export const PLOT_KINDS = ['found', 'fall', 'hold', 'war', 'ally', 'capital', 'death', 'crown', 'split', 'disaster', 'submit', 'peace', 'dynasty', 'revolt', 'collapse', 'story'] as const;
export type PlotKind = (typeof PLOT_KINDS)[number];
